import Foundation
import Observation
import os.log

/// Server session information returned by the API.
///
/// Represents the current state of a terminal session running on the Untether server,
/// including its command, directory, and process status. Field names match `Session` in
/// web/src/shared/types.ts; fields added after the original set are `var` with a default so
/// the memberwise initializer keeps working without them.
struct ServerSessionInfo: Codable, Equatable, Sendable {
    let id: String
    let name: String
    let command: [String]
    let workingDir: String
    let status: String
    let exitCode: Int?
    let startedAt: String
    let pid: Int?
    let initialCols: Int?
    let initialRows: Int?
    let lastClearOffset: Int?
    let version: String?
    let gitRepoPath: String?
    let gitBranch: String?
    let gitAheadCount: Int?
    let gitBehindCount: Int?
    let gitHasChanges: Bool?
    let gitIsWorktree: Bool?
    let gitMainRepoPath: String?

    // Additional fields from Session (not SessionInfo)
    let lastModified: String
    let active: Bool?
    let activityStatus: SessionActivityStatus?
    let source: String?
    let remoteId: String?
    let remoteName: String?
    let remoteUrl: String?
    let attachedViaUT: Bool?

    // Git status details (fetched dynamically by the server)
    var gitModifiedCount: Int?
    var gitUntrackedCount: Int?
    var gitStagedCount: Int?
    var gitAddedCount: Int?
    var gitDeletedCount: Int?

    // Titles and agent state
    /// The title the user gave the session (rename); wins over every other title.
    var userTitle: String?
    /// Claude Code running in this session.
    var claudeStatus: ClaudeStatus?
    /// Claude's conversation title, kept after the session exits.
    var claudeTitle: String?
    /// OpenAI Codex session: its first prompt, as the conversation title.
    var codexTitle: String?
    /// Google Gemini CLI session: its first prompt, as the conversation title.
    var geminiTitle: String?
    var codexActive: Bool?
    var geminiActive: Bool?
    /// Running non-Claude session: the last line of output on screen (at most 120 characters).
    var lastLine: String?
    var muted: Bool?
    /// Runs in a private tmux session that survives server restarts.
    var shielded: Bool?
    /// Suspended by the server to free memory (web services/session-suspender.ts): it wakes
    /// when opened. Listed with the running ones, marked paused.
    var suspended: SessionSuspensionInfo?

    var isRunning: Bool {
        self.status == "running"
    }

    /// Paused by the server, not finished: it stays in the menu.
    var isSuspended: Bool {
        self.suspended != nil
    }

    /// Determine whether the session should be considered active for UI purposes.
    ///
    /// The activity monitor flag is authoritative since Mac app and server ship together.
    var isActivityActive: Bool {
        self.activityStatus?.isActive ?? false
    }
}

/// What the menu reads of a suspended session (`suspended` in web/src/shared/types.ts).
struct SessionSuspensionInfo: Codable, Equatable, Sendable {
    /// When it was suspended (ISO).
    let at: String?
    /// The last wake failed: why.
    let resumeError: String?
    /// The project it orchestrated when it was suspended (it stays listed under it).
    var orchestratorOf: String?
}

/// Activity status for a session.
struct SessionActivityStatus: Codable, Equatable, Sendable {
    let isActive: Bool
    let lastActivityAt: String?
}

/// Claude Code's state in a session (`claudeStatus` in web/src/shared/types.ts).
///
/// Every field is optional so a change on the server side never breaks decoding of the whole list.
struct ClaudeStatus: Codable, Equatable, Sendable {
    /// "idle", "busy" or "waiting" (for the user).
    let status: String?
    /// What Claude waits for, in Claude Code's words ("permission prompt").
    let waitingFor: String?
    /// Conversation title generated by Claude Code.
    let title: String?
    /// Last user or assistant message, one line.
    let preview: ClaudePreview?
    /// While busy: what Claude is doing right now.
    let activity: ClaudeActivity?
    /// While waiting: the menu on screen and what it is about ("Bash command", the command).
    let choices: ClaudeChoices?
    /// When the current status began (epoch ms).
    let since: Double?
    /// Busy only because background agents or tasks still run.
    let waitingForBackground: Bool?
}

struct ClaudePreview: Codable, Equatable, Sendable {
    /// "user" or "assistant".
    let role: String?
    let text: String?
}

struct ClaudeChoices: Codable, Equatable, Sendable {
    let question: String?
    let options: [String]?
    let detail: [String]?
}

struct ClaudeActivity: Codable, Equatable, Sendable {
    /// "thinking", "writing" or "tool".
    let kind: String?
    let tool: String?
    let target: String?
    let since: Double?
}

/// Lightweight session monitor that fetches terminal sessions on-demand.
///
/// Manages the collection of active terminal sessions by periodically polling
/// the server API and caching results for efficient access. Provides real-time
/// session information to the UI with minimal network overhead.
@MainActor
@Observable
final class SessionMonitor {
    static let shared = SessionMonitor()

    /// The last good snapshot of the server's sessions. A failed fetch keeps it (2026-10-12: a
    /// single failed poll emptied the menu and said "No active sessions" while sessions ran).
    private(set) var sessions: [String: ServerSessionInfo] = [:]
    /// Running sessions, prepared for display (titles, state, dates), rebuilt only on change.
    private(set) var displays: [SessionDisplay] = []
    /// Sessions that have a terminal window on this Mac (from WindowTracker, read once per fetch
    /// so views never take WindowTracker's lock in `body`).
    private(set) var windowSessionIds: Set<String> = []
    private(set) var lastError: Error?
    /// The last fetch failed although the server is supposed to run: `sessions` may be stale.
    private(set) var isServerUnreachable = false
    /// A fetch has completed (or failed) at least once since launch: before that, an empty list
    /// means "loading", not "no sessions".
    private(set) var hasLoaded = false

    private var lastFetch: Date?
    private let cacheInterval: TimeInterval = 2.0
    private let serverManager = ServerManager.shared
    private let logger = Logger(subsystem: BundleIdentifiers.loggerSubsystem, category: "SessionMonitor")

    /// Reference to GitRepositoryMonitor for pre-caching
    weak var gitRepositoryMonitor: GitRepositoryMonitor?

    private init() {}

    /// Set the local auth token for server requests
    func setLocalAuthToken(_ token: String?) {}

    /// Number of running sessions
    var sessionCount: Int {
        self.sessions.values.count { $0.isRunning }
    }

    /// Number of running sessions whose agent waits for the user.
    var needsYouCount: Int {
        self.displays.count { $0.state == .needsYou }
    }

    /// Get all sessions, using cache if available
    func getSessions() async -> [String: ServerSessionInfo] {
        // Use cache if available and fresh
        if let lastFetch, Date().timeIntervalSince(lastFetch) < cacheInterval {
            return self.sessions
        }

        await self.fetchSessions()
        return self.sessions
    }

    /// Force refresh session data
    func refresh() async {
        self.lastFetch = nil
        await self.fetchSessions()
    }

    // MARK: - Private Methods

    private func fetchSessions() async {
        // No server, no sessions: don't hit the network every second for nothing.
        guard self.serverManager.isRunning else {
            self.apply(sessions: [:])
            self.isServerUnreachable = false
            self.lastFetch = Date()
            return
        }

        do {
            let sessionsArray = try await serverManager.performRequest(
                endpoint: APIEndpoints.sessions,
                method: "GET",
                responseType: [ServerSessionInfo].self)

            var sessionsDict: [String: ServerSessionInfo] = [:]
            for session in sessionsArray {
                sessionsDict[session.id] = session
            }

            let changed = self.apply(sessions: sessionsDict)
            if self.lastError != nil { self.lastError = nil }
            if self.isServerUnreachable { self.isServerUnreachable = false }
            self.lastFetch = Date()

            // Update WindowTracker, then read which sessions have a window once for the views
            WindowTracker.shared.updateFromSessions(sessionsArray)
            let windowIds = Set(sessionsArray.lazy.map(\.id).filter {
                WindowTracker.shared.windowInfo(for: $0) != nil
            })
            if windowIds != self.windowSessionIds { self.windowSessionIds = windowIds }

            // Fill in git details the server did not send
            if changed, let gitMonitor = gitRepositoryMonitor {
                self.preCacheGitRepositories(for: sessionsArray, using: gitMonitor)
            }
        } catch {
            // Only update error if it's not a simple connection error
            if !(error is URLError) {
                self.lastError = error
            }
            self.logger.error("Failed to fetch sessions: \(error, privacy: .public)")
            // Keep the last good snapshot; the menu says the server can't be reached.
            if !self.isServerUnreachable { self.isServerUnreachable = true }
            self.lastFetch = Date() // Still update timestamp to avoid hammering
        }
        if !self.hasLoaded { self.hasLoaded = true }
    }

    /// Store a new snapshot only when it differs, so observers don't redraw on every poll.
    @discardableResult
    private func apply(sessions newSessions: [String: ServerSessionInfo]) -> Bool {
        guard newSessions != self.sessions else { return false }
        self.sessions = newSessions
        let newDisplays = newSessions.values
            .filter { $0.isRunning || $0.isSuspended }
            .map(SessionDisplay.init(info:))
            .sorted { $0.id < $1.id }
        if newDisplays != self.displays { self.displays = newDisplays }
        return true
    }

    /// Pre-cache Git repositories the server reported without change counts, once per repository.
    /// The server's git fields come first; sessions outside a repository are not probed.
    private func preCacheGitRepositories(
        for sessions: [ServerSessionInfo],
        using gitMonitor: GitRepositoryMonitor)
    {
        var uniqueDirectoriesToCheck = Set<String>()
        for session in sessions where session.isRunning {
            guard let repoPath = session.gitRepoPath, session.gitModifiedCount == nil else { continue }
            if gitMonitor.getCachedRepository(for: repoPath) != nil { continue }
            uniqueDirectoriesToCheck.insert(repoPath)
        }
        guard !uniqueDirectoriesToCheck.isEmpty else { return }

        for directory in uniqueDirectoriesToCheck {
            Task {
                // This will cache the data for immediate access later
                _ = await gitMonitor.findRepository(for: directory)
            }
        }

        self.logger.debug(
            "Pre-caching Git data for \(uniqueDirectoriesToCheck.count) repositories (from \(sessions.count) sessions)")
    }
}
